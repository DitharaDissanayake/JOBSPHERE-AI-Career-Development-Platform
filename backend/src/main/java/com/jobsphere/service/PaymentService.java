package com.jobsphere.service;

import com.jobsphere.entity.Course;
import com.jobsphere.entity.CoursePayment;
import com.jobsphere.entity.User;
import com.jobsphere.repository.CoursePaymentRepository;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.Locale;
import java.util.UUID;

@Service
public class PaymentService {
    public static final BigDecimal ADVANCED_PRICE = new BigDecimal("250.00");
    private final CoursePaymentRepository payments;
    private final EmailService email;

    public PaymentService(CoursePaymentRepository payments, EmailService email) {
        this.payments = payments;
        this.email = email;
    }

    public CoursePayment createPending(Long userId, Long courseId, String gateway) {
        CoursePayment p = new CoursePayment();
        p.userId=userId;
        p.courseId=courseId;
        p.orderId="JS-"+System.currentTimeMillis()+"-"+UUID.randomUUID().toString().substring(0,8).toUpperCase(Locale.ROOT);
        p.amount=ADVANCED_PRICE;
        p.currency="LKR";
        p.status="PENDING";
        p.gateway=gateway;
        p.createdAt=LocalDateTime.now();
        return payments.save(p);
    }

    public CoursePayment markPaid(CoursePayment p, User user, Course course,
                                  String paymentId, String method, String brand, String last4) throws Exception {
        if ("PAID".equalsIgnoreCase(p.status)) return p;
        p.status="PAID";
        p.paymentId=paymentId;
        p.paymentMethod=method;
        p.cardBrand=brand;
        p.cardLast4=last4;
        p.paidAt=LocalDateTime.now();
        p.invoiceFileName="JOBSPHERE-Payment-"+p.orderId+".pdf";
        p.invoiceData=createInvoicePdf(user, course, p);
        payments.save(p);

        try {
            email.sendCoursePaymentInvoice(user.email, user.fullName, course.name,
                    p.orderId, p.paymentId, p.amount.setScale(2).toPlainString(),
                    p.invoiceData, p.invoiceFileName);
            p.emailSent=true;
            payments.save(p);
        } catch (Exception ex) {
            // Payment remains valid even if SMTP is temporarily unavailable.
            p.emailSent=false;
            payments.save(p);
        }
        return p;
    }

    private byte[] createInvoicePdf(User user, Course course, CoursePayment p) throws Exception {
        ByteArrayOutputStream out=new ByteArrayOutputStream();
        try(PDDocument doc=new PDDocument()){
            PDPage page=new PDPage(PDRectangle.A4);
            doc.addPage(page);
            try(PDPageContentStream s=new PDPageContentStream(doc,page)){
                float w=PDRectangle.A4.getWidth();
                s.setLineWidth(2); s.addRect(36,36,w-72,PDRectangle.A4.getHeight()-72); s.stroke();
                text(s,"JOBSPHERE",PDType1Font.HELVETICA_BOLD,24,60,750);
                text(s,"COURSE PAYMENT RECEIPT",PDType1Font.HELVETICA_BOLD,18,60,710);
                text(s,"Payment successful",PDType1Font.HELVETICA_BOLD,13,60,675);
                line(s,"Learner",safe(user.fullName),635);
                line(s,"Email",safe(user.email),605);
                line(s,"Course",safe(course.name),575);
                line(s,"Course type","Advanced 7-Day Course",545);
                line(s,"Amount","LKR "+p.amount.setScale(2).toPlainString(),515);
                line(s,"Order ID",p.orderId,485);
                line(s,"Payment ID",safe(p.paymentId),455);
                line(s,"Method",safe(p.paymentMethod),425);
                if(p.cardLast4!=null && !p.cardLast4.isBlank()) line(s,"Card","**** **** **** "+p.cardLast4,395);
                line(s,"Status","PAID",365);
                line(s,"Paid at",String.valueOf(p.paidAt),335);
                text(s,"Thank you for learning with JOBSPHERE.",PDType1Font.HELVETICA,11,60,270);
                text(s,"This receipt was generated by the JOBSPHERE Career Development Platform.",PDType1Font.HELVETICA,9,60,245);
            }
            doc.save(out);
        }
        return out.toByteArray();
    }

    private void line(PDPageContentStream s,String label,String value,float y) throws Exception{
        text(s,label,PDType1Font.HELVETICA_BOLD,11,60,y);
        text(s,value,PDType1Font.HELVETICA,11,190,y);
    }
    private void text(PDPageContentStream s,String value,PDType1Font font,float size,float x,float y)throws Exception{
        s.beginText(); s.setFont(font,size); s.newLineAtOffset(x,y); s.showText(safe(value)); s.endText();
    }
    private String safe(String s){
        if(s==null||s.isBlank()) return "-";
        return s.replace("\n"," ").replace("\r"," ").replace("–","-").replace("—","-")
                .replace("“","\"").replace("”","\"").replace("’","'");
    }
}
